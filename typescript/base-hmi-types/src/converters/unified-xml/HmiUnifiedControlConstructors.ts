const constructors: Record<string, new () => object> = { HmiAlarmControl, HmiAlarmIndicator, HmiAlarmLineControl, HmiBar, HmiButton, HmiCheckBoxGroup, HmiCircle, HmiCircleSegment, HmiCircularArc, HmiClock, HmiCustomWebControlContainer, HmiCustomWidgetContainer, HmiDetailedParameterControl, HmiEllipse, HmiEllipseSegment, HmiEllipticalArc, HmiFaceplateContainer, HmiFunctionTrendControl, HmiGauge, HmiGraphicView, HmiIOField, HmiLabel, HmiLine, HmiListBox, HmiMediaControl, HmiPolygon, HmiPolyline, HmiProcessControl, HmiProcessDiagnosisCriteriaAnalysisControl, HmiProcessDiagnosisGraphOverviewControl, HmiProcessDiagnosisOverviewControl, HmiProcessDiagnosisPlcCodeViewerControl, HmiRadioButtonGroup, HmiRectangle, HmiScreenWindow, HmiSlider, HmiSymbolicIOField, HmiSystemDiagnosisControl, HmiText, HmiTextBox, HmiToggleSwitch, HmiTouchArea, HmiTrendCompanion, HmiTrendControl, HmiWebControl };
export function unifiedControlConstructor(name: string): (new () => HmiScreenItemBase) | undefined {
    if(name === "HmiCustomWebControlContainer") return HmiCustomWidgetContainer;
    const type = constructors[name === 'HmiSwitch' ? 'HmiToggleSwitch' : name];
    return type && type.prototype instanceof HmiScreenItemBase ? type as new () => HmiScreenItemBase : undefined;
}
