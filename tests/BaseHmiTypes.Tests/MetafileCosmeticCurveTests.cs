[TestClass]
public class MetafileCosmeticCurveTests
{
    public static IEnumerable<object[]> NativeFixtures()
    {
        using var stream=typeof(MetafileCosmeticCurveTests).Assembly.GetManifestResourceStream("BaseHmiTypes.Tests.Fixtures.cosmetic-curves.json")!;
        using var document=JsonDocument.Parse(stream);
        foreach(var entry in document.RootElement.EnumerateArray())yield return new object[]{entry.GetProperty("Index").GetInt32(),entry.GetProperty("Source").GetString()!,entry.GetProperty("Hash").GetString()!};
    }

    private static string MaskHash(string text,int index)
    {
        var svg=XDocument.Parse(text);var mask=new byte[6400];
        if(index%12==8)Assert.IsTrue(svg.Descendants().Any(e=>e.Attribute("clip-path")!=null));
        foreach(var path in svg.Descendants().Where(e=>e.Name.LocalName=="path"&&e.Attribute("fill")?.Value is "#123456" or "#ff0000"))
            foreach(Match point in Regex.Matches(path.Attribute("d")!.Value,@"M (-?\d+) (-?\d+)h1v1h-1Z"))
            {
                var x=int.Parse(point.Groups[1].Value);var y=int.Parse(point.Groups[2].Value);
                if(x<0||x>=80||y<0||y>=80||index%12==8&&(x<15||x>=55||y<10||y>=45))continue;
                mask[y*80+x]=path.Attribute("fill")!.Value=="#123456"?(byte)1:(byte)2;
            }
        return Convert.ToHexString(SHA256.HashData(mask)).ToLowerInvariant();
    }

    // Generated by WinccFileFormat/tools/GdiPenReference --curves, not by either renderer.
    [TestMethod] [DynamicData(nameof(NativeFixtures))]
    public void CurvesMatchNativeGdiMask(int index,string source,string hash)
    {
        var bytes=Convert.FromBase64String(source.Split(',')[1]);
        Assert.AreEqual(hash,MaskHash(new MetafileToSvgRenderer().Render(bytes,".emf")!,index));
    }

    [TestMethod]
    public async Task HtmlPreservesNativeCurveAndOriginalSource()
    {
        var fixture=NativeFixtures().First();var source=(string)fixture[1];var item=new HmiGraphicView{Name="Curve",Source=source};
        var screen=new HmiScreen();var layer=new HmiLayer();screen.Layers.Add(layer);layer.Items.Add(item);
        var html=await new HmiScreenToHtmlConverter().ConvertAsync(screen);
        var match=Regex.Match(html,"src=\"data:image/svg\\+xml;charset=utf-8,([^\"]+)\"");Assert.IsTrue(match.Success);
        Assert.AreEqual(fixture[2],MaskHash(Uri.UnescapeDataString(match.Groups[1].Value),0));Assert.AreEqual(source,item.Source!.StaticValue);
    }

    [TestMethod]
    public void FractionalTransformsUseNativePixelStrokes()
    {
        var bytes=Emf(Record(38,1,1,1,0,0x563412),Record(37,1),Record(35,BitConverter.SingleToInt32Bits(1),0,0,BitConverter.SingleToInt32Bits(1),BitConverter.SingleToInt32Bits(.25f),0),Record(2,0,0,39,39,4,4,30,10,4,30,4,36,30));
        var svg=new MetafileToSvgRenderer().Render(bytes,".emf")!;StringAssert.Contains(svg,"h1v1h-1Z");Assert.IsFalse(svg.Contains("C "));
    }

    [TestMethod]
    public void OversizedCurveRetainsAtomicVectorFallback()
    {
        var bytes=Emf(Record(38,1,1,1,0,0x563412),Record(37,1),Record(2,0,0,39,39,4,4,30,int.MaxValue,4,30,int.MinValue,36,30));
        var svg=new MetafileToSvgRenderer().Render(bytes,".emf")!;StringAssert.Contains(svg,"C ");Assert.IsFalse(svg.Contains("h1v1h-1Z"));
    }
}
